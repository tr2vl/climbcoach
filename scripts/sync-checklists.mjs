// Copies HERO_CHECKLISTS.md (shared with the Mac app) into src/shared/checklists-text.js.
// Run after the checklists change; the tests fail when a hero in the catalog has no checklist.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const text = fs.readFileSync(path.resolve(here, '..', '..', 'HERO_CHECKLISTS.md'), 'utf8');
const out = `// Generated by scripts/sync-checklists.mjs from HERO_CHECKLISTS.md. Do not edit by hand.\nexport const CHECKLISTS_TEXT = ${JSON.stringify(text)};\n`;
fs.writeFileSync(path.resolve(here, '..', 'src', 'shared', 'checklists-text.js'), out);
console.log(`Wrote checklists ${text.match(/^Version: (\S+)/m)?.[1]}`);
