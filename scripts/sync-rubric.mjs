// Copies RUBRIC.md (the Mac app's single source of truth for scoring) into src/shared/rubric-text.js.
// The "Meaning for you" column is written for the Mac app's owner, so the Windows copy drops it:
// your rank goes into every prompt as a match fact instead. Run after the rubric changes.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const source = path.resolve(here, '..', '..', 'RUBRIC.md');
let text = fs.readFileSync(source, 'utf8');
const table = /\| Score \| Level the play looks like \| Meaning for you \([^)]*\) \|\n\|---\|---\|---\|\n((?:\|[^\n]*\|\n)+)/;
const match = text.match(table);
if (!match) throw new Error('The scale table in RUBRIC.md changed; update sync-rubric.mjs.');
const rows = match[1].trim().split('\n').map((row) => row.split('|').slice(1, 3).map((cell) => cell.trim()));
text = text.replace(table, `| Score | Level the play looks like |\n|---|---|\n${rows.map(([score, level]) => `| ${score} | ${level} |`).join('\n')}\n`);
const version = text.match(/^# Rating Rubric v([\d.]+)/m)?.[1];
const out = `// Generated by scripts/sync-rubric.mjs from RUBRIC.md. Do not edit by hand.\nexport const RUBRIC_VERSION = ${JSON.stringify(version)};\nexport const RUBRIC_TEXT = ${JSON.stringify(text)};\n`;
fs.writeFileSync(path.resolve(here, '..', 'src', 'shared', 'rubric-text.js'), out);
console.log(`Wrote rubric v${version}`);
